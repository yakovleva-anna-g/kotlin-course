//1. Определите функцию-расширение для массива чисел, которая не принимает аргументов
// и возвращает пару из чисел - первое и последнее. Если массив был пуст то вернуть пару из null значений.

fun Array<Int>.ex1(): Pair<Int?, Int?> {
    if (this.isEmpty()) {
        return Pair(null, null)
    } else {
        return this.first() to this.last()
    }
}

