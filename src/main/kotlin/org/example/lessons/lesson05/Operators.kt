ОПЕРАТОРЫ ИНКРЕМЕНТА И ДЕКРЕМЕНТА
В Kotlin, как и во многих других языках программирования, существуют операторы инкремента (++)
и декремента (--). Эти операторы используются для увеличения или уменьшения значения переменной на единицу соответственно.
Использование
Операторы инкремента и декремента часто используются в циклах и при работе с коллекциями для сокращения кода и повышения его читаемости.

Префиксный и Постфиксный Форматы
Инкремент и декремент могут использоваться в двух формах: префиксной и постфиксной.

Префиксный Формат (++variable, --variable): операция выполняется первой, затем возвращается значение.

Например, ++counter сначала увеличивает counter на 1, а затем возвращает новое значение counter.

Постфиксный Формат (variable++, variable--): сначала возвращается текущее значение переменной, затем выполняется операция.

Например, counter++ сначала возвращает текущее значение counter, а затем увеличивает его на 1.

var a = 5
var b = a++
println("a: $a")
println("b: $b")

var c = 5
var d = ++c
println("c: $c")
println("d: $d")
В примере с a и b, b получает значение a до увеличения, в то время как в примере с c и d, d получает значение c после увеличения.

Приоритеты арифметических и логических операций в Kotlin
Арифметические операции
В Kotlin арифметические операции следуют традиционным математическим правилам приоритета:

Скобки  ( )  имеют самый высокий приоритет и используются для явного указания порядка выполнения операций.

Умножение ( * ) и деление ( / ) идут следующими. Они выполняются до сложения и вычитания.

Сложение ( + ) и вычитание ( - ) имеют самый низкий приоритет среди арифметических операций.

Логические операции:
Логические операции в Kotlin также следуют определенному порядку приоритета:

Логическое НЕ ( ! ) имеет самый высокий приоритет. Оно инвертирует значение своего операнда.

Логическое И ( && ) выполняется после логического НЕ. Оператор && возвращает true, только если оба операнда истинны.

Логическое ИЛИ ( || ) имеет самый низкий приоритет. Оператор || возвращает true, если хотя бы один из операндов истинен.

Пример:

Выражение 3 + 4 * 5 равно 23, а не 35, потому что умножение имеет более высокий приоритет и выполняется первым, так что это 3 + (4 * 5).

Выражение !(true && false) || false равно true. Сначала вычисляется true && false, что равно false, затем !false, что равно true, и в конце true || false, что также равно true.

Оператор Элвиса (?:)
Оператор Элвиса используется для предоставления альтернативного значения в случае, если выражение слева от оператора равно null.

val name: String? = null
val result = name ?: "Unknown" // "Unknown", так как name равно null
