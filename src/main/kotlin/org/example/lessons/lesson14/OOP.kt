//  ТИП  Object
//    object в Kotlin используется для создания синглтонов, то есть классов, которые могут иметь только
//    один экземпляр. Это удобно, когда вам нужен глобальный объект, например, менеджер конфигурации или логгер.
    // у ОБЪЕКТОВ конструкторов типа object Logger (val p2:String) нет, потому что этот объект является одновременно и классом и экземпляром

    object Logger { // сущность объявляется как object и можем вывести его через main в отличие от классов
        fun log(message: String) {
            println("Log: $message")
        }
    }

//    Здесь Logger — это синглтон, и его методы доступны без создания экземпляра.
//
