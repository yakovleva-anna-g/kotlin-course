//Объектно-ориентированное программирование (ООП) - это парадигма программирования, которая использует "объекты"
// для моделирования данных и поведения программы. Основные концепции ООП включают классы и объекты,
// наследование, инкапсуляцию, полиморфизм и абстракцию.
//
//Классы и объекты
//Класс в ООП определяется как шаблон или чертёж, который описывает состояние и поведение, которыми
// обладает объект этого класса. Класс состоит из полей или атрибутов и методов или функций (или процедур).


// методы или функции - это действия, то есть, то что может заорать внезапно, то что может крутиться,
// то что может бежать или может считать проценты по кредиту
//
// поля или атрибуты - это статические, то есть переменные которые хранятся в классе, это
// какие-то объекты, или это нечто что содержит данные. Это данные которые просто лежат и что с ними не происходит
// пока эти данные не попадают в методы, которые можно как-то преобразовать или изменить
//
//Объект - это экземпляр класса (экземпляр это какая-то единица).
// (класс у нас описывает чертеж и из этого чертежа создают объект, например: есть какой-то чертеж транспортного средства
// и из него создают объект, конкретный объект автомобиля, в который можно сесть завести или включить фары ...)
// Когда класс определен, ни один из его содержащихся методов или переменных
// не используется, пока не будет создан объект этого класса. Объекты создаются и уничтожаются динамически
// и могут иметь множество экземпляров одного класса.
//
//Основная структура класса в Kotlin
//В Kotlin класс объявляется с использованием ключевого слова class. Внутри класса могут быть поля (свойства)
// и методы (функции). Пример базового класса:

