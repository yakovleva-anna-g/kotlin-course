//Полиморфизм в ООП — это принцип, позволяющий одному и тому же имени функции
// (или метода) работать по-разному в зависимости от контекста.
// Это достигается двумя основными способами: перегрузкой и переопределением.
//
//Перегрузка (Overloading): Это когда один и тот же метод может принимать
// разное количество или типы параметров. Например, функция add может
// складывать как два числа, так и объединять две строки.
// Выбор конкретной реализации метода зависит от типов и количества аргументов,
// переданных при вызове.
//
//Переопределение (Overriding): Это когда производный класс изменяет
// реализацию метода, унаследованного от базового класса.
// Так, метод базового класса и его производные классы могут иметь разное
// поведение, несмотря на то что вызывается одно и то же имя метода.
// Это позволяет объектам производных классов реагировать по-разному на одни и
// те же сообщения (вызовы методов).
//
//Вспомним, что метод - это действие. Название метода должно характеризовать
// это действие. Например Монитор. Действие - показывать изображение (show()).
//
//Переопределение. Для разных мониторов способ вывода изображения будет разным,
// но результат действия будет сопоставим между собой.
//
//Перегрузка. Метод show() может принимать разные источники изображения
// (VGA, HDMI, DisplayPort). Для этого в классе монитора будет три метода,
// которые принимают разные типы подключения,
// но выполнять будут сопоставимые между собой действия.

