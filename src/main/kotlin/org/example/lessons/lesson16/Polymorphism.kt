// же функцию - проиграть определённый набор нот.
// Полиморфизм в программировании похож на этот оркестр:
// разные объекты могут использовать один и тот же метод,
// но каждый из них выполняет его по-своему, внося свой уникальный вклад в общее дело.
//
//Переопределение так же называют динамический полиморфизм — это принцип ООП,
// который позволяет объектам разных классов обрабатывать данные с использованием
// одноименных методов, но реализованных по-разному.

