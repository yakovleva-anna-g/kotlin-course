package org.example.lessons.lesson22

import java.io.IOException


//Дерево основных классов исключений
//В Kotlin все исключения наследуются от класса Throwable. Основные подклассы:
//
//Error: Ошибки, связанные с проблемами в работе виртуальной машины Java и которые
// обычно не предполагают обработку в программе (например, OutOfMemoryError).
//Exception: Исключения, которые должны быть обработаны в программе. Делятся на:
//IOException: Исключения, связанные с вводом-выводом.
//RuntimeException: Исключения времени выполнения, которые могут быть выброшены
// во время выполнения программы из-за ошибок в логике программы
// (например, NullPointerException, IndexOutOfBoundsException).
//Разница между Error и Exception
//Error: Указывает на серьезные проблемы, которые приложение не должно пытаться обработать.
//Exception: Исключения, с которыми приложение может и должно справиться.
//Синтаксис выбрасывания исключений
//Чтобы выбросить исключение, используйте ключевое слово throw,
// за которым следует экземпляр исключения:

fun main() {


// можно выкидывать исключение из переменной
    val exception = Exception("Сообщение об ошибке")
    throw exception

//Синтаксис отлова исключений
//Используйте блок try-catch для отлова (перехватывания) исключений:

    try {
        // Код, который может выбросить исключение
    } catch (e: IOException) {
        // Обработка конкретного типа исключения
    } catch (e: Exception) {
        // Обработка всех остальных исключений
    } finally {
        // Блок, который выполняется всегда, независимо от наличия исключения
    }
  //  Отлов исключений нескольких типов
    // В Kotlin для одновременного отлова нескольких типов исключений используется
    // конструкция when в блоке catch . Вот как это должно выглядеть на практике :

    try {
        // Код, который может выбросить исключения
    } catch (e: Exception) {
        when (e) {
            is IndexOutOfBoundsException -> {
                println("Обработано исключение типа IndexOutOfBoundsException")
            }

            is RuntimeException -> {
                println("Обработано исключение типа RuntimeException")
            }

            else -> throw e // Перебрасываем исключение дальше, если оно не соответствует обработанным типам
        }
    }
}