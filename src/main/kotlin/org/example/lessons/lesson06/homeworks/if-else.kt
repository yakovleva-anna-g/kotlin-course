//Создайте функцию, которая конвертирует температуру(convertTemp) из градусов Цельсия ('C') в Фаренгейты ('F') и
// наоборот в
// зависимости от указанной единицы измерения (C/F). Единицу измерения нужно передать вторым аргументом функции.
// Несколько аргументов передаются через запятую. Распечатай в консоль результат конвертации с добавлением
// единицы измерения. Чтобы добавить единицу измерения после результата используй функцию печати без переноса
// строки print("C") или print("F").

fun example6(value: Int, unit: Char) {
    when (unit) {
        'C' -> {
            val fahrenheit = value * 1.8 + 32
            print(fahrenheit)
            print(" F")
            println()
        }
        'F' -> {
            val celsius = (value - 32) * 1.8
            print(celsius)
            print(" C")
            println()
        }
        else -> {
            println("Ошибка")
        }
    }
}


